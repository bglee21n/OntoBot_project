def main() -> None:
    text = MD.read_text(encoding="utf-8")
    marker = "\n## 25.1 "
    if INTRO.strip() not in text:
        text = text.replace(marker, "\n" + INTRO + marker, 1)
    for cat, note in NOTES.items():
        text = text.replace(f"<!-- notes:{cat} -->", note)
    MD.write_text(text, encoding="utf-8")
    print("해설을 끼웠습니다:", MD)


if __name__ == "__main__":
    main()
